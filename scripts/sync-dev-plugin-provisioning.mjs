#!/usr/bin/env node

import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { loadEnvFile } from 'node:process';
import { fileURLToPath } from 'node:url';
import { parse, stringify } from 'yaml';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, '..');
const defaultBasePath = path.join(repositoryRoot, 'provisioning/plugins/app.yaml');
const defaultOutputPath = path.join(repositoryRoot, 'work/dev-provisioning/plugins/app.yaml');
const defaultConfigMapKey = 'grafana-assistant-app.yaml';
const defaultSourcePluginId = 'grafana-assistant-app';

loadRepositoryEnv();

const options = parseOptions(process.argv.slice(2));

if (options.help) {
  printHelp();
  process.exit(0);
}

const basePath = resolveRepositoryPath(options.base ?? process.env.PI_PLUGIN_PROVISIONING_BASE ?? defaultBasePath);
const outputPath = resolveRepositoryPath(
  options.output ??
    process.env.PI_PLUGIN_PROVISIONING_OUTPUT ??
    process.env.PI_PLUGIN_PROVISIONING_FILE ??
    defaultOutputPath
);
const configuredSource = options.source ?? process.env.PI_SKILLS_CONFIG_SOURCE;
const configMapKey = options.configMapKey ?? process.env.PI_SKILLS_CONFIG_MAP_KEY ?? defaultConfigMapKey;
const sourcePluginId = options.sourcePluginId ?? process.env.PI_SKILLS_SOURCE_PLUGIN_ID ?? defaultSourcePluginId;

const baseText = await readFile(basePath, 'utf8');
let outputText = baseText;

if (configuredSource) {
  const sourcePath = resolveRepositoryPath(configuredSource);
  const sourceText = await readFile(sourcePath, 'utf8');
  const sourceProvisioning = readSourceProvisioning(sourceText, configMapKey, sourcePath);
  const sourceApp = findApp(sourceProvisioning, sourcePluginId, sourcePath);
  const customSkills = sourceApp.jsonData?.customSkills;

  validateCustomSkills(customSkills, sourcePath);

  const stringsWithUnescapedDollars = countStringsWithUnescapedDollars(customSkills);

  if (stringsWithUnescapedDollars > 0) {
    console.warn(
      `Warning: ${stringsWithUnescapedDollars} imported custom skill string(s) contain unescaped dollar signs. ` +
        'Grafana provisioning expands dollar expressions; use $$ in the source for each literal $.'
    );
  }

  const localProvisioning = parseYamlDocument(baseText, basePath);
  const localApp = findLocalApp(localProvisioning, basePath);
  localApp.jsonData ??= {};
  localApp.jsonData.customSkills = customSkills;

  outputText = [
    '# Generated by scripts/sync-dev-plugin-provisioning.mjs. Do not edit.',
    '# customSkills imported from the configured local source.',
    '',
    stringify(localProvisioning, { lineWidth: 0 }),
  ].join('\n');

  console.log(`Imported ${customSkills.length} custom skills from the configured local source.`);
} else {
  console.log('PI_SKILLS_CONFIG_SOURCE is not set; using the repository customSkills configuration.');
}

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, outputText.endsWith('\n') ? outputText : `${outputText}\n`, 'utf8');
console.log(`Wrote development plugin provisioning to ${outputPath}`);

function loadRepositoryEnv() {
  const envPath = path.join(repositoryRoot, '.env');

  if (existsSync(envPath)) {
    loadEnvFile(envPath);
  }
}

function resolveRepositoryPath(value) {
  return path.isAbsolute(value) ? value : path.resolve(repositoryRoot, value);
}

function parseOptions(args) {
  const parsed = {};

  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];

    if (argument === '--help' || argument === '-h') {
      parsed.help = true;
      continue;
    }

    const [name, inlineValue] = argument.split('=', 2);
    const value = inlineValue ?? args[++index];

    if (!value || value.startsWith('--')) {
      throw new Error(`Missing value for ${name}`);
    }

    switch (name) {
      case '--base':
        parsed.base = value;
        break;
      case '--output':
        parsed.output = value;
        break;
      case '--source':
        parsed.source = value;
        break;
      case '--config-map-key':
        parsed.configMapKey = value;
        break;
      case '--source-plugin-id':
        parsed.sourcePluginId = value;
        break;
      default:
        throw new Error(`Unknown option: ${name}`);
    }
  }

  return parsed;
}

function readSourceProvisioning(sourceText, configMapKey, sourcePath) {
  const embeddedProvisioning = extractLiteralBlock(sourceText, configMapKey);

  if (embeddedProvisioning !== undefined) {
    return parseYamlDocument(embeddedProvisioning, `${sourcePath}#data.${configMapKey}`);
  }

  const sourceDocument = parseYamlDocument(sourceText, sourcePath);

  if (Array.isArray(sourceDocument?.apps)) {
    return sourceDocument;
  }

  const dataValue = sourceDocument?.data?.[configMapKey];

  if (typeof dataValue === 'string') {
    return parseYamlDocument(dataValue, `${sourcePath}#data.${configMapKey}`);
  }

  throw new Error(
    `${sourcePath} is neither a plugin provisioning document nor a ConfigMap containing data.${configMapKey}`
  );
}

function extractLiteralBlock(sourceText, key) {
  const lines = sourceText.replaceAll('\r\n', '\n').split('\n');
  const escapedKey = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const keyPattern = new RegExp(`^(\\s*)(?:["']?${escapedKey}["']?):\\s*[|>][+-]?\\s*$`);
  const keyLineIndex = lines.findIndex((line) => keyPattern.test(line));

  if (keyLineIndex < 0) {
    return undefined;
  }

  const keyIndent = lines[keyLineIndex].match(/^\s*/)[0].length;
  const blockLines = [];

  for (let index = keyLineIndex + 1; index < lines.length; index += 1) {
    const line = lines[index];
    const indent = line.match(/^\s*/)[0].length;

    if (line.trim() && indent <= keyIndent) {
      break;
    }

    blockLines.push(line);
  }

  const contentIndent = Math.min(
    ...blockLines.filter((line) => line.trim()).map((line) => line.match(/^\s*/)[0].length)
  );

  if (!Number.isFinite(contentIndent)) {
    return '';
  }

  return blockLines.map((line) => (line.trim() ? line.slice(contentIndent) : '')).join('\n');
}

function parseYamlDocument(value, sourceLabel) {
  let document;

  try {
    document = parse(value);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    throw new Error(`Cannot parse YAML from ${sourceLabel}: ${message}`);
  }

  if (!isRecord(document)) {
    throw new Error(`Expected ${sourceLabel} to contain a YAML object`);
  }

  return document;
}

function findApp(provisioning, pluginId, sourceLabel) {
  if (!Array.isArray(provisioning.apps)) {
    throw new Error(`Expected ${sourceLabel} to contain an apps array`);
  }

  const app = provisioning.apps.find((candidate) => isRecord(candidate) && candidate.type === pluginId);

  if (!app) {
    throw new Error(`Could not find app type ${pluginId} in ${sourceLabel}`);
  }

  return app;
}

function findLocalApp(provisioning, sourceLabel) {
  if (!Array.isArray(provisioning.apps)) {
    throw new Error(`Expected ${sourceLabel} to contain an apps array`);
  }

  const app = provisioning.apps.find(
    (candidate) => isRecord(candidate) && (candidate.type === '$__env{PI_PLUGIN_ID}' || candidate.type === 'g42-pi-app')
  );

  if (!app) {
    throw new Error(`Could not find the local Pi app entry in ${sourceLabel}`);
  }

  return app;
}

function validateCustomSkills(customSkills, sourceLabel) {
  if (!Array.isArray(customSkills)) {
    throw new Error(`Expected ${sourceLabel} jsonData.customSkills to be an array`);
  }

  if (customSkills.length > 20) {
    throw new Error(`${sourceLabel} contains ${customSkills.length} custom skills; the plugin limit is 20`);
  }

  const names = new Set();

  customSkills.forEach((skill, index) => {
    const label = `customSkills[${index}]`;

    if (!isRecord(skill)) {
      throw new Error(`${sourceLabel} ${label} must be an object`);
    }

    if (typeof skill.name !== 'string' || !/^[a-z0-9](?:[a-z0-9-]{0,62}[a-z0-9])?$/.test(skill.name)) {
      throw new Error(`${sourceLabel} ${label}.name must be a valid kebab-case skill name`);
    }

    if (names.has(skill.name)) {
      throw new Error(`${sourceLabel} contains duplicate custom skill ${skill.name}`);
    }

    names.add(skill.name);

    if (typeof skill.description !== 'string' || !skill.description.trim()) {
      throw new Error(`${sourceLabel} ${label}.description is required`);
    }

    if (typeof skill.content !== 'string' || !skill.content.trim()) {
      throw new Error(`${sourceLabel} ${label}.content is required`);
    }

    if (skill.content.length > 20_000) {
      throw new Error(`${sourceLabel} ${label}.content exceeds the 20000 character plugin limit`);
    }

    if (skill.resources !== undefined && !Array.isArray(skill.resources)) {
      throw new Error(`${sourceLabel} ${label}.resources must be an array`);
    }

    if (skill.resources?.length > 20) {
      throw new Error(`${sourceLabel} ${label}.resources exceeds the 20 resource plugin limit`);
    }
  });
}

function isRecord(value) {
  return Boolean(value) && typeof value === 'object' && !Array.isArray(value);
}

function countStringsWithUnescapedDollars(value) {
  if (typeof value === 'string') {
    return [...value.matchAll(/\$+/g)].some((match) => match[0].length % 2 !== 0) ? 1 : 0;
  }

  if (Array.isArray(value)) {
    return value.reduce((count, item) => count + countStringsWithUnescapedDollars(item), 0);
  }

  if (isRecord(value)) {
    return Object.values(value).reduce((count, item) => count + countStringsWithUnescapedDollars(item), 0);
  }

  return 0;
}

function printHelp() {
  console.log(`Usage: node scripts/sync-dev-plugin-provisioning.mjs [options]

Generate the ignored development plugin provisioning file used by Docker Compose.
When a source is configured, jsonData.customSkills is copied from the selected app.

Options:
  --source <path>             Plugin provisioning YAML or Helm ConfigMap template
  --base <path>               Local base provisioning file
  --output <path>             Generated provisioning file
  --config-map-key <key>      ConfigMap data key (default: ${defaultConfigMapKey})
  --source-plugin-id <id>     Source app type (default: ${defaultSourcePluginId})
  --help                      Show this help

The matching environment variables are PI_SKILLS_CONFIG_SOURCE,
PI_PLUGIN_PROVISIONING_BASE, PI_PLUGIN_PROVISIONING_OUTPUT,
PI_PLUGIN_PROVISIONING_FILE, PI_SKILLS_CONFIG_MAP_KEY, and
PI_SKILLS_SOURCE_PLUGIN_ID.`);
}
